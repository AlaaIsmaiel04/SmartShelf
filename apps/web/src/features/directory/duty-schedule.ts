export const publishedDuties: PublishedDuty[] = days.flatMap(
  ([day, ...pharmacies]) =>
    pharmacies.map(([name, address], index) => ({
      date: `2026-11-${day}`,
      shift: index < 2 ? ('noon' as const) : ('evening' as const),
      name,
      address,
    })),
);

export function filterPublishedDuties(
  date: string,
  name: string,
  shift: string,
) {
  const query = name.trim().normalize('NFKC');
  return publishedDuties.filter(
    (entry) =>
      (!date || entry.date === date) &&
      (!shift || entry.shift === shift) &&
      (!query ||
        entry.name.normalize('NFKC').includes(query) ||
        entry.address.normalize('NFKC').includes(query)),
  );
}
